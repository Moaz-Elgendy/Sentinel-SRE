"""
DOCUMENTATION — build the post-incident record.

Produces five sections for every incident:
  1. Timeline of lifecycle events with timestamps
  2. Root cause analysis narrative
  3. Impact assessment
  4. Resolution summary
  5. Preventive actions

The record is always written to SQLite (that is the authoritative copy). A
GitHub issue and a Slack message are optional delivery channels.

### Hard constraint

Sentinel **never modifies application code and never merges anything.** There
is no branch push, no pull request, no file write outside its own data
directory. Preventive actions that involve a code change are written as
*prose in the issue body* for a human to implement.

That boundary is deliberate and worth stating plainly: an agent authorised to
restart a Deployment has a bounded, reversible blast radius that recovery
validation can check. An agent authorised to change the code has an unbounded
one that no runtime check can verify. Those are different risk classes and
this project only takes the first.

The markdown is generated by string templating rather than by an LLM, so the
document is deterministic and reproducible from the incident record. The LLM
narrative, when present, is embedded as one clearly-labelled section.
"""
